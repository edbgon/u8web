def find_game_file(game_dir, name):
    """Case-insensitively locate `name` anywhere under a U8 game install.

    The game ships its data spread across STATIC/, GAMEDAT/, SOUND/ and
    USECODE/ with all-uppercase DOS names. A few files (e.g. U8SHAPES.FLX)
    exist in more than one place — STATIC/ holds the canonical originals,
    so it is preferred when there is a choice.
    """
    name_l = name.lower()
    matches = []
    for dirpath, _, files in os.walk(game_dir):
        for f in files:
            if f.lower() == name_l:
                matches.append(os.path.join(dirpath, f))
    if not matches:
        raise FileNotFoundError(
            f"'{name}' not found under game directory '{game_dir}'. "
            f"Pass the correct path with --game-dir.")
    matches.sort(key=lambda p: 0 if os.path.basename(
        os.path.dirname(p)).upper() == "STATIC" else 1)
    return matches[0]

# ──────────────────────────────────────────────
# Low-level readers
# ──────────────────────────────────────────────
def u8(d, o):  return d[o]
def u16(d, o): return struct.unpack_from("<H", d, o)[0]
def i16(d, o): return struct.unpack_from("<h", d, o)[0]
def u24(d, o): return d[o] | (d[o+1] << 8) | (d[o+2] << 16)
def u32(d, o): return struct.unpack_from("<I", d, o)[0]
def load(path):
    with open(path, "rb") as f:
        return f.read()

# ──────────────────────────────────────────────
# Shape info  (U8SHAPES.FLX)
# ──────────────────────────────────────────────
def parse_shapes(path):
    data  = load(path)
    count = u32(data, 84)
    tbl   = 144
    result = {}
    for i in range(count):
        off = u32(data, tbl + i * 8)
        ln  = u32(data, tbl + i * 8 + 4)
        if off == 0 or ln == 0:
            continue
        base   = off
        n_frm  = u16(data, base + 4)
        fhbase = base + 6
        frames = []
        for j in range(n_frm):
            fh       = fhbase + j * 6
            frm_off  = u24(data, fh)
            frm_base = base + frm_off
            if frm_base + 18 > len(data):
                continue
            frm_idx = u16(data, frm_base + 2)
            frames.append({
                "fi": frm_idx if frm_idx != 0 else j,
                "sx": i16(data, frm_base + 10),
                "sy": i16(data, frm_base + 12),
                "ox": i16(data, frm_base + 14),
                "oy": i16(data, frm_base + 16),
            })
        result[i] = frames

    # The player Avatar (shape 1) isn't a normal shape: its frames live in
    # FLX entry 1, which the +2-biased loop above never reads (it starts the
    # index table at 144, i.e. real entry 2). Parse it under key -1 so that
    # merge_shapes' lookup, shape_info.get(obj["s"] - 2), resolves shape 1.
    av_off = u32(data, 128 + 1 * 8)
    if av_off:
        n_frm  = u16(data, av_off + 4)
        frames = []
        for j in range(n_frm):
            frm_base = av_off + u24(data, av_off + 6 + j * 6)
            if frm_base + 18 > len(data):
                continue
            frm_idx = u16(data, frm_base + 2)
            frames.append({
                "fi": frm_idx if frm_idx != 0 else j,
                "sx": i16(data, frm_base + 10),
                "sy": i16(data, frm_base + 12),
                "ox": i16(data, frm_base + 14),
                "oy": i16(data, frm_base + 16),
            })
        result[-1] = frames
    return result

# ──────────────────────────────────────────────
# Object parsers
# ──────────────────────────────────────────────
OBJ_FMT  = "<HHBHBHHBBH"
OBJ_SIZE = 16
# Object status-flags word (`_f`). Bit 0x0008 = item is inside a container
# (Pentagram Item::FLG_CONTAINED) — those items must not render on the map.
FLG_CONTAINED = 0x0008
# FIXED.DAT record `idx` is the game map number; the per-map JSON files (and
# the viewer's map indices) are biased off it by this amount.
FIXED_INDEX_BIAS = -2

def parse_objects(data, offset, length, include_glob=False, container_shapes=None,
                  quality_shapes=None):
    """
    Parse a sequence of 16-byte object records.

    NONFIXED.DAT interleaves world-placed items with the contents of any
    containers (chests, NPC inventories, etc.) and nested containers within.
    When iterating, items inside a container have their first u16 field
    overloaded to encode container depth instead of world-x. Container-depth
    tracking keeps these inventory entries out of the top-level object list
    (they would otherwise render at junk screen positions derived from the
    depth markers) and instead nests each under its container object as a
    `c` list, so the viewer can show the container's gump with its contents.
    """
    objects = []
    contdepth = 0
    # depth → the container object whose direct contents live at that depth.
    # Lets contained items be nested under their container as a `c` list so
    # the viewer can show the container's gump with its contents inside.
    container_at = {}
    for i in range(length // OBJ_SIZE):
        base = offset + i * OBJ_SIZE
        (x, y, z, shape, frame, _f, quality, npcnum, mapnum, _x2) = \
            struct.unpack_from(OBJ_FMT, data, base)
        if container_shapes is not None:
            while contdepth != x and contdepth > 0:
                contdepth -= 1
            depth = contdepth
        else:
            depth = 0
        # depth > 0 → the item sits inside container_at[depth]. The
        # FLG_CONTAINED bit also marks contained items the depth heuristic
        # misses (when the container's shape isn't a container family).
        contained = depth > 0 or bool(_f & FLG_CONTAINED)

        obj = {"x": x, "y": y, "z": z, "s": shape, "f": frame}
        if include_glob and shape == 2:
            obj["g"] = quality
        # Shape-73 eggs encode their usecode class in `quality` (Pentagram's
        # Item::callUsecodeEvent: class_id = quality + 0x47F for SF_UNKEGG)
        # and their Egg ID in `mapnum` (Egg::getEggId returns mapnum).
        # Keep both so the globswap pass can dispatch correctly.
        if shape == 73:
            obj["quality"] = quality
            obj["eggid"] = mapnum
        # Shape-562 MUSIC eggs (usecode class 562) call playMusic(quality)
        # on Event 4 (cachein) when quality != 0. Save quality so we can
        # publish per-map music data alongside the map index.
        elif shape == 562:
            obj["quality"] = quality
        # Shape-500 monster eggs (Pentagram's MonsterEgg, ShapeInfo family
        # SF_MONSTEREGG=7). `quality` packs the monster: shape = quality &
        # 0x7FF, spawn probability = (quality >> 11) & 0x1F.
        elif shape == 500:
            obj["quality"] = quality
        # Shape-508 teleport eggs (Pentagram's TeleportEgg, ShapeInfo family
        # SF_TELEPORTEGG). `quality & 0xFF` is the teleport id. frame == 1
        # marks a teleport *target* (the landing pad); any other frame is an
        # active teleporter whose `mapnum` field is the destination map
        # (TeleportEgg::hatch → av->teleport(mapnum, telId)). The matching
        # destination is the frame-1 egg on that map with the same teleport
        # id — see CurrentMap::findDestination. Store both so the viewer can
        # jump to the exact landing egg.
        elif shape == 508:
            obj["telid"] = quality & 0xFF
            if frame != 1:
                obj["teledest"] = mapnum + FIXED_INDEX_BIAS
        # Books / scrolls / keys (shapes listed in json/barks.json with a
        # quality table) pick their description by quality — keep it so the
        # viewer can show the right title in the inspector.
        if quality_shapes and shape in quality_shapes:
            obj["descq"] = quality

        if not contained:
            objects.append(obj)
        elif depth > 0 and depth in container_at:
            container_at[depth].setdefault("c", []).append(obj)
        # else: FLG_CONTAINED but the depth heuristic lost the container —
        # drop it (it would otherwise render at a junk world position).

        if container_shapes is not None and shape in container_shapes:
            contdepth += 1
            container_at[contdepth] = obj
            for d in [k for k in container_at if k > contdepth]:
                del container_at[d]
    return objects


def contents_tree(items):
    """Compact a container's nested `c` list (built by parse_objects) into the
    map-JSON trailer form: each entry is {s,f} plus q (quality, used to resolve
    a readable's text) and c (nested contents) when present."""
    out = []
    for it in items:
        e = {"s": it["s"], "f": it["f"]}
        if it.get("descq"):
            e["q"] = it["descq"]
        if it.get("c"):
            e["c"] = contents_tree(it["c"])
        out.append(e)
    return out

def parse_typeflags(path):
    data = load(path)
    result = {}
    record_size = 8
    count = len(data) // record_size
    for i in range(count):
        base = i * record_size
        b0 = u8(data, base + 0)
        b1 = u8(data, base + 1)
        b2 = u8(data, base + 2)
        b3 = u8(data, base + 3)
        b4 = u8(data, base + 4)
        b5 = u8(data, base + 5)
        translucent    = (b1 >> 3) & 1
        family         = (b1 >> 4) & 15        # container shapes have family == 6
        size_x         = (b2 >> 4) & 15
        size_y         = (b3 >> 0) & 15
        size_z         = (b3 >> 4) & 15
        animation_type = (b4 >> 0) & 15
        animation_data = (b4 >> 4) & 15
        hide_in_game   = (b5 >> 4) & 1

        draw     = (b1 >> 0) & 1
        solid    = (b0 >> 1) & 1
        occluding= (b0 >> 4) & 1

        entry = {}
        if family == 6:    entry["isContainer"]   = True
        if translucent:    entry["translucent"]   = True
        if animation_type: entry["animationType"] = animation_type
        if animation_data: entry["animationData"] = animation_data
        if hide_in_game:   entry["hideInGame"]    = True
        if draw:           entry["draw"]          = True
        if solid:          entry["solid"]         = True
        if occluding:      entry["occl"]          = True

        is_ground_tile  = (max(size_x, 1) == 4 and max(size_y, 1) == 4)
        is_32x32_ground = (size_x == 4 and size_y == 4 and size_z == 0)

        entry["draw"] = 1 if draw else 0
        entry["xd"]     = size_x * 32
        entry["yd"]     = size_y * 32
        entry["zd"]     = size_z * 8

        entry["foot_x"] = size_x * 32
        entry["foot_y"] = size_y * 32
        # foot_z is the true z-dimension of the bounding box.
        # Zero IS legal – flat tiles have foot_z == 0.
        entry["foot_z"] = size_z * 8
        entry["flat"]   = 1 if size_z == 0 else 0
        entry["f32"]    = 1 if size_x == 4 and size_y == 4 and size_z == 0 else 0

        result[i] = entry
    return result

def parse_globs(path):
    data  = load(path)
    count = u32(data, 84)
    tbl   = 128
    globs = {}
    for i in range(count):
        off = u32(data, tbl + i * 8)
        ln  = u32(data, tbl + i * 8 + 4)
        if off == 0 or ln == 0:
            continue
        base      = off
        obj_count = u16(data, base)
        objs      = []
        ptr       = base + 2
        for _ in range(obj_count):
            x     = u8(data, ptr + 0)
            y     = u8(data, ptr + 1)
            z     = u8(data, ptr + 2)
            shape = u16(data, ptr + 3)
            frame = u8(data, ptr + 5)
            objs.append({"x": x, "y": y, "z": z, "s": shape, "f": frame})
            ptr += 6
        globs[i] = objs
    return globs

def apply_globswap(objects):
    """
    Statically resolve Pentagram's GLOBSWAP usecode (class 1200).

    A GLOBSWAP "destination" egg (shape 73, quality 49 → usecode class
    49 + 0x47F = 1200) at enterFastArea finds its matching "source" egg —
    shape 73, quality 47 for pre-quake or quality 48 for post-quake state,
    paired by EggId (the `mapnum` field per Pentagram's Egg::getEggId) — and
    copies every non-egg item from the source's 512×512 world chunk into the
    destination's chunk. New positions take the source's low 9 bits OR'd with
    the destination's chunk-high bits; z is offset by the destination egg's z.

    To support a runtime toggle in the viewer, we emit BOTH variants. Items
    teleported from a quality-47 source are tagged `_quake = 1` (pre-quake
    only), quality-48 from `_quake = 2` (post-quake only). Untagged items
    (no `_quake` key) are always visible. The dest-chunk cleanup destroys
    non-egg / non-glob items that exist in both states equally, so it runs
    once before insertion.

    Without this pass, areas of certain maps appear as one-chunk holes (e.g.
    floors in map 48) because their actual content lives parked in
    the bottom-right corner of the world space, never moved into place.
    """
    dest_eggs = [o for o in objects if o["s"] == 73 and o.get("quality") == 49]
    if not dest_eggs:
        return objects

    src_by_quality = {47: {}, 48: {}}
    for o in objects:
        if o["s"] != 73:
            continue
        q = o.get("quality")
        if q in src_by_quality:
            src_by_quality[q].setdefault(o.get("eggid"), o)

    # Cleanup is identical for pre/post — strip non-egg, non-glob items from
    # every destination chunk before laying down the teleported content.
    # Mirror the disassembled GLOBSWAP usecode (class 1200,
    # Func_80 enterFastArea) exactly. Cleanup destroys non-egg / non-glob
    # items in each dest chunk (matched by `& 0x7E00`, the chunk-index mask
    # the usecode uses). Then for each source quality, spawn copies of each
    # non-egg item from the source egg's chunk into the dest chunk with:
    #   new_x = (src.x & 0x1FF) | (dest.x & 0x7E00)
    #   new_y = (src.y & 0x1FF) | (dest.y & 0x7E00)
    #   new_z = dest.z + src.z      (both treated as signed bytes, then added)
    CHUNK_MASK = 0x7E00
    LOCAL_MASK = 0x1FF
    dest_chunks = {(d["x"] & CHUNK_MASK, d["y"] & CHUNK_MASK) for d in dest_eggs}
    out = [
        o for o in objects
        if not (
            (o["x"] & CHUNK_MASK, o["y"] & CHUNK_MASK) in dest_chunks
            and o["s"] != 73 and o["s"] != 2
        )
    ]

    def ubyte(v):
        return v & 0xFF

    for dest in dest_eggs:
        eid = dest.get("eggid")
        dest_cx = dest["x"] & CHUNK_MASK
        dest_cy = dest["y"] & CHUNK_MASK
        for src_quality, quake_tag in [(47, 1), (48, 2)]:
            src = src_by_quality[src_quality].get(eid)
            if not src:
                continue
            src_cx = src["x"] & CHUNK_MASK
            src_cy = src["y"] & CHUNK_MASK
            for o in objects:
                if (o["x"] & CHUNK_MASK) != src_cx or (o["y"] & CHUNK_MASK) != src_cy:
                    continue
                if o["s"] == 73:
                    continue
                new_obj = dict(o)
                new_obj["x"] = (o["x"] & LOCAL_MASK) | dest_cx
                new_obj["y"] = (o["y"] & LOCAL_MASK) | dest_cy
                new_obj["z"] = (ubyte(dest["z"]) + ubyte(o["z"])) & 0xFF
                new_obj["_quake"] = quake_tag
                out.append(new_obj)
    return out


def apply_collapse(objects):
    """
    Simulate the COLLAPSE trap (usecode class 525, "It's a trap") gotHit
    handler. For each hidden shape-525 trigger (foot 64×64×0), find the
    shape-521 "Big floor" (foot 256×256×8) whose top sits at the trap's z
    and whose 2D footprint overlaps the trap. Tag the intact floor with
    `_collapse=1` (visible pre-trigger) and emit four shape-519/520
    "Crumbling floor" edge pieces with `_collapse=2` (visible post-trigger).

    The four pieces match the gotHit handler at COLLAPSE+0x123 exactly:
      shape 519, frame = floor.f*30 + 0,  pos (x-192, y-64,  z)
      shape 519, frame = floor.f*30 + 15, pos (x,     y,     z)
      shape 520, frame = floor.f*30 + 0,  pos (x,     y-192, z)
      shape 520, frame = floor.f*30 + 15, pos (x-64,  y,     z)
    where (x,y,z) is the floor's anchor (+x,+y,+z corner per U8 convention).
    """
    traps = [o for o in objects if o["s"] == 525]
    if not traps:
        return objects

    out = list(objects)

    # Cache floor lookup by their +x,+y corner for fast pairing.
    floors = [o for o in objects if o["s"] == 521]

    pieces = []
    consumed_floor_ids = set()
    for trap in traps:
        tx, ty, tz = trap["x"], trap["y"], trap["z"]
        # Match: top (z+foot_z=8) at trap.z, 2D footprint overlaps trap's
        # 64×64 footprint. Floor anchor is the +x,+y corner; it covers
        # (x-256, y-256] × (y-256, y]. Tag every overlapping floor so we
        # don't leave a sibling tile rendering over the collapse.
        trap_x0, trap_x1 = tx - 64, tx
        trap_y0, trap_y1 = ty - 64, ty
        matches = []
        for fl in floors:
            if id(fl) in consumed_floor_ids:
                continue
            if fl["z"] + 8 != tz:
                continue
            fx, fy = fl["x"], fl["y"]
            if fx - 256 >= trap_x1 or fx <= trap_x0:
                continue
            if fy - 256 >= trap_y1 or fy <= trap_y0:
                continue
            matches.append(fl)
        if not matches:
            continue
        for match in matches:
            consumed_floor_ids.add(id(match))
            match["_collapse"] = 1
            fx, fy, fz, ff = match["x"], match["y"], match["z"], match["f"]
            base_frame = (ff * 30) & 0xFFFF
            # Pentagram's COLLAPSE::029D spawn animates the piece by
            # incrementing frame each tick until (frame+1)%15==0, then ret.
            # Static view: show the final crumbled-state frame (cycle end).
            for sshape, fr_off, dx, dy in [
                (519, 14, -192, -64),
                (519, 29,  0,    0),
                (520, 14,  0,   -192),
                (520, 29, -64,   0),
            ]:
                pieces.append({
                    "x": fx + dx,
                    "y": fy + dy,
                    "z": fz,
                    "s": sshape,
                    "f": (base_frame + fr_off) & 0xFFFF,
                    "_collapse": 2,
                })
    out.extend(pieces)
    return out


# Front-facing idle frame per monster shape, eyeballed from the labeled
# sheets dump_monster_frames.py writes to tools/monsters/. Used by apply_monster_eggs.
MONSTER_POSE_FRAME = {
    76: 46,  81: 4,   83: 69,  96: 55,  119: 47, 120: 50, 142: 113,
    214: 62, 269: 56, 357: 100, 411: 134, 413: 20, 509: 42, 574: 70,
    707: 4,  708: 4,  806: 7,  807: 27, 808: 13, 824: 8,
}


# The four Titans — Hydros (80), Pyros (109), Stratos (385), Lithos (433) —
# are placed in the maps at frame 0: their dormant, un-manifested pose, whose
# sprite is all but empty. In-game the usecode animates them into a visible
# form; a static viewer can't, so swap in a hand-picked "manifested" frame so
# each Titan is actually visible and clickable at its normal spot.
TITAN_DISPLAY_FRAME = {80: 28, 109: 20, 385: 10, 433: 25}


def apply_titan_frames(objects):
    """Rewrite each Titan object's frame to its manifested display pose."""
    for obj in objects:
        df = TITAN_DISPLAY_FRAME.get(obj["s"])
        if df is not None:
            obj["f"] = df
    return objects


def apply_monster_eggs(objects, atlas_frames):
    """Reveal the creature hidden inside each shape-500 monster egg.

    Shape 500 has ShapeInfo family SF_MONSTEREGG (7); the game keeps it
    invisible and, on hatching, spawns an actor of shape `quality & 0x7FF`
    at the egg's position (Pentagram's MonsterEgg::hatch / getMonsterShape).
    There is no usecode class 500 — the behaviour lives entirely in the
    engine. For a static viewer we just retarget the egg to the monster
    shape so the proper creature sprite is drawn where the egg sits.

    The monster is shown on a hand-picked front-facing idle frame per shape
    (MONSTER_POSE_FRAME) — sprite sheets are inconsistent, so these were
    eyeballed from dump_monster_frames.py's labeled sheets. A shape with no
    entry falls back to the 16th sprite the atlas holds for it.

    Eggs whose monster shape is 0 hatch nothing (MonsterEgg::hatch bails on
    shape 0) and are left as the inert hidden egg.
    """
    pose = {}   # monster shape -> frame index to display
    for o in objects:
        if o["s"] != 500:
            continue
        monster_shape = (o.get("quality", 0)) & 0x7FF
        if monster_shape == 0:
            continue
        if monster_shape not in pose:
            frame = MONSTER_POSE_FRAME.get(monster_shape)
            if frame is None or f"{monster_shape}_{frame}" not in atlas_frames:
                # No curated pose (or it's not packed): fall back to the
                # 16th atlas sprite, else the last one available.
                avail = sorted(int(k[len(str(monster_shape)) + 1:])
                               for k in atlas_frames
                               if k.startswith(f"{monster_shape}_"))
                frame = avail[min(16, len(avail) - 1)] if avail else 0
            pose[monster_shape] = frame
        o["s"] = monster_shape
        o["f"] = pose[monster_shape]
        o["_monster"] = 1
    return objects


def expand_globs(objects, globs):
    out = []
    for obj in objects:
        if obj.get("g") is None:
            out.append(obj)
            continue
        glob_objs = globs.get(obj["g"])
        if not glob_objs:
            continue
        bx, by, bz = obj["x"], obj["y"], obj["z"]
        base_x = bx & ~0x1FF
        base_y = by & ~0x1FF
        quake = obj.get("_quake")
        for g in glob_objs:
            child = {
                "x": g["x"] * 2 + base_x,
                "y": g["y"] * 2 + base_y,
                "z": bz + g["z"],
                "s": g["s"],
                "f": g["f"],
                "_glob": True,
            }
            if quake:
                child["_quake"] = quake
            out.append(child)
    return out

