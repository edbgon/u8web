        FALLBACK_GUMP = 9
        containers_json = json.dumps(
            {int(s): (g if g in ccomp else FALLBACK_GUMP)
             for s, g in container_gumps.items()
             if g in ccomp or FALLBACK_GUMP in ccomp},
            separators=(",", ":"))
