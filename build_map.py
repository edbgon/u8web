def build_all(
    game_dir      = DEFAULT_GAME_DIR,
    labels_json   = "./json/labels.json",
    barks_json    = "./json/barks.json",
    image_folder  = "shapes",
    maps_dir      = "maps",
    output_html   = "map.html",
):
    # Resolve the binary inputs straight out of the game install — no copying.
    print(f"Using game directory: {game_dir}")
    shapes_flx   = find_game_file(game_dir, "U8SHAPES.FLX")
    fixed_dat    = find_game_file(game_dir, "FIXED.DAT")
    nonfixed_dat = find_game_file(game_dir, "NONFIXED.DAT")
    globs_dat    = find_game_file(game_dir, "GLOB.FLX")
    typeflag_dat = find_game_file(game_dir, "TYPEFLAG.DAT")

    maps_path = Path(maps_dir)
    maps_path.mkdir(exist_ok=True)
    print("Loading shape info…")
    shape_info = parse_shapes(shapes_flx)

    print("Loading type flags…")
    typeflags = parse_typeflags(typeflag_dat)
    combined = {}

    print("Parsing globs…")
    globs = parse_globs(globs_dat)

    # Per-object descriptions extracted from the usecode (json/parse_usecode.py).
    # {shape: {default?, frames?, quality?}} — drives the inspector's text.
    print("Loading barks…")
    barks = {}
    barks_path = Path(barks_json)
    if barks_path.exists():
        with open(barks_path, "r", encoding="utf-8") as f:
            barks = json.load(f)
    else:
        print(f"  (no {barks_json} — run parse_usecode.py; skipping)")
    quality_shapes = {int(s) for s, e in barks.items() if "quality" in e}
    # Keys + locks (doors / chests) — quality is the shared lock id, so we
    # keep it on every instance to drive the inspector's key↔lock cross-link.
    KEY_SHAPES  = {79, 82, 232}
    LOCK_SHAPES = {68, 69, 78, 114, 117, 135, 340, 341, 342, 618, 673}
    # Chests don't store their lock id directly. Pentagram's KEYRING usecode
    # (class 79 fn at 0x119) iterates each chest's contents looking for a
    # shape-756 (Trap) item whose quality high byte is 1; the low byte is the
    # chest's lock id. We track 756 here so the quality byte survives parsing
    # for that lookup. (Trap items with high byte 0 are real damage traps,
    # untouched by this logic.)
    LOCK_TRAP_SHAPE = 756
    quality_shapes |= KEY_SHAPES | LOCK_SHAPES | {LOCK_TRAP_SHAPE}

    # Readable shapes (books/scrolls/tombstones/plaques) also pick their text
    # by quality, so their quality must survive into the row trailer too.
    readables_for_q = {}
    rpath = Path("json/readables.json")
    if rpath.exists():
        with open(rpath, "r", encoding="utf-8") as f:
            readables_for_q = json.load(f)
    quality_shapes |= {int(s) for s, e in readables_for_q.items()
                       if "quality" in e}

    print("Parsing fixed map info…")
    fdata, frecords = read_fixed(fixed_dat)
    print("Parsing dynamic map info…")
    ndata, nrecords = read_nonfixed(nonfixed_dat)
    container_shapes = {s for s, tf in typeflags.items() if tf.get("isContainer")}

    # Container shape → gump backdrop (raw U8GUMPS.FLX entry number). The
    # gump is guessed from the shape's label — U8's container names ("Chest",
    # "Wooden Barrel", "Backpack", "Wardrobe", …) map cleanly onto the gump
    # artwork. json/containers.json overrides the guess per shape; anything
    # still unresolved falls back to the chest gump so every container opens.
    # Keyword order matters: longer/more-specific names are checked first
    # ("backpack" before "pack", "wardrobe"/"jewel" share the jewelry gump).
    # gumps.json keys, verified against the actual gumps.png artwork:
    #   4 backpack · 5 cloth bag/sack · 6 barrel · 9 treasure chest ·
    #   12 jewelry box · 13 crate · 14 corpse/skull · 15 drawer · 16 basket.
    CONTAINER_GUMP_KEYWORDS = [
        # "Big cabinet" in labels.json is the in-game wardrobe — share the
        # drawer gump rather than the jewelry-box one.
        ("wardrobe", 15), ("cabinet", 15),
        ("jewerly", 12), ("jewelry", 12), ("jewel", 12),
        ("drawer", 15), ("desk", 15),
        ("backpack", 4), ("basket", 16), ("barrel", 6),
        ("pouch", 5), ("sack", 5), ("bag", 5),
        ("chest", 9), ("crate", 13),
        ("corpse", 14), ("skeleton", 14), ("remains", 14),
        ("bones", 14), ("body", 14), ("dead", 14),
        ("pack", 4),
    ]
    DEFAULT_CONTAINER_GUMP = 9
    container_labels = {}
    labels_path = Path(labels_json)
    if labels_path.exists():
        with open(labels_path, "r", encoding="utf-8") as f:
            container_labels = json.load(f)
    container_gump_overrides = {}
    containers_path = Path("json/containers.json")
    if containers_path.exists():
        with open(containers_path, "r", encoding="utf-8") as f:
            container_gump_overrides = {int(k): int(v)
                                        for k, v in json.load(f).items()}

    def guess_container_gump(shape):
        name = (container_labels.get(str(shape)) or "").lower()
        for kw, gump in CONTAINER_GUMP_KEYWORDS:
            if kw in name:
                return gump
        return DEFAULT_CONTAINER_GUMP

    container_gumps = {s: container_gump_overrides.get(s, guess_container_gump(s))
                       for s in container_shapes}

    # Container gump item areas: U8 ships static/GUMPAGE.DAT — 8 bytes per
    # gump shape (x, y, x2, y2 as sint16 LE), the rectangle inside the gump
    # art where contained items are drawn (Pentagram GumpShapeArchive::
    # loadGumpage). The table is 1-indexed by U8GUMPS.FLX entry number; this
    # project's gump ids carry the +2 atlas bias, so entry = gump_id - 2.
    gumpage_areas = {}
    try:
        gp = Path(find_game_file(game_dir, "GUMPAGE.DAT")).read_bytes()
        for i in range(len(gp) // 8):
            x, y, x2, y2 = struct.unpack_from("<hhhh", gp, i * 8)
            if x2 > x and y2 > y:
                gumpage_areas[i + 1] = [x, y, x2 - x, y2 - y]
    except FileNotFoundError:
        print("  (no GUMPAGE.DAT — container windows use proportional insets)")

    # Gather per-map raw objects from BOTH FIXED and NONFIXED before any
    # post-processing — the GLOBSWAP pass needs to see destination eggs
    # (often in NONFIXED) together with their source-chunk content (often
    # in FIXED), and glob expansion needs to happen after teleport so
    # teleported glob references expand at their new anchor.
    per_map_raw = {}
    for idx, off, ln in frecords:
        real_idx = idx + FIXED_INDEX_BIAS
        if real_idx < 0: continue
        # FIXED.DAT also interleaves container contents (dead bodies, urns,
        # etc.) right after their container, depth-encoded in the x field the
        # same way NONFIXED.DAT does — parse with container_shapes so those
        # items get nested as `c` lists instead of dropped on the FLG_CONTAINED
        # check.
        objs = parse_objects(fdata, off, ln, include_glob=True,
                             container_shapes=container_shapes,
                             quality_shapes=quality_shapes)
        per_map_raw.setdefault(real_idx, []).extend(objs)
    for idx, off, ln in nrecords:
        # NONFIXED.DAT mixes world objects with the contents of containers
        # (NPC inventories, chests, etc.). Container-depth tracking drops
        # inventory entries so they don't render at junk positions.
        objs = parse_objects(ndata, off, ln, include_glob=True,
                             container_shapes=container_shapes,
                             quality_shapes=quality_shapes)
        per_map_raw.setdefault(idx, []).extend(objs)

    # Per-map music: pull quality from every shape-562 MUSIC egg before any
    # of the post-processing passes (apply_globswap leaves them in place,
    # but this keeps the lookup simple). One playMusic(quality) call per egg;
    # most maps have a single egg, a few have multiple regions.
    music_by_map = {}
    for real_idx, raw in per_map_raw.items():
        qualities = []
        for o in raw:
            if o["s"] == 562:
                q = o.get("quality")
                if q:
                    qualities.append(q)
        if qualities:
            # Deduplicate but preserve order.
            seen = []
            for q in qualities:
                if q not in seen:
                    seen.append(q)
            music_by_map[real_idx] = seen

    # The viewer renders every sprite out of atlas.png; build_render_objects
    # uses this set to skip objects whose (shape, frame) the atlas lacks.
    atlas_frames = set()
    atlas_path = Path("json/atlas.json")
    if atlas_path.exists():
        with open(atlas_path) as f:
            atlas_frames = set(json.load(f).get("frames", {}).keys())
    else:
        print("WARNING: json/atlas.json missing — run build_atlas.py first")

    # NPCs live in ITEMCACH.DAT/NPCDATA.DAT, not the per-map object lists.
    # Drop each onto its home map so it flows through the same pipeline.
    # ITEMCACH stores the *game* map number; per_map_raw is keyed by the
    # internal index, which is FIXED_INDEX_BIAS off from it.
    npcs_by_map = parse_npcs(game_dir, atlas_frames)
    npc_count = 0
    npc_template = {}   # npc_id -> {s, f}  for ghost placements below
    npc_home_map = {}   # npc_id -> real_idx (the ITEMCACH home)
    npc_home_xy  = {}   # npc_id -> (x, y) — ITEMCACH home coords as a consensus seed
    for mapnum, npcs in npcs_by_map.items():
        real_idx = mapnum + FIXED_INDEX_BIAS
        if real_idx in per_map_raw:
            per_map_raw[real_idx].extend(npcs)
            npc_count += len(npcs)
        for n in npcs:
            npc_template[n["_npc"]] = {"s": n["s"], "f": n["f"],
                                        "z": n["z"]}
            npc_home_map.setdefault(n["_npc"], real_idx)
            npc_home_xy.setdefault(n["_npc"], (n["x"], n["y"]))
    print(f"Placed {npc_count} NPCs across {len(npcs_by_map)} maps")

    # NPC schedule waypoints (parse_schedules.py): infer which map each
    # waypoint belongs to by world-coord bbox containment, then add a
    # "ghost" NPC marker on every map that has waypoints but is not the
    # ITEMCACH home. ITEMCACH parks most named Tenebrae NPCs on the Docks
    # map (mapnum 3 = real_idx 1) as a boot position, but their schedule
    # coords are valid for the per-region maps (West/Central/East Tenebrae,
    # etc.). Without ghosts the user can only select the NPC on the boot
    # map, where the schedule projects to garbage positions.
    schedules = {}
    sched_path_load = Path("json/schedules.json")
    if sched_path_load.exists():
        with open(sched_path_load, "r", encoding="utf-8") as f:
            schedules = json.load(f)

    # Object-density grid per map. Bbox-containment alone misclassifies
    # waypoints because most U8 maps have outlier objects that stretch
    # their bbox to the full 0..65535 coord space; the *play area* is much
    # tighter. Quantising to 1024-unit cells and counting top-level
    # objects per cell gives a local-density signal that picks the map
    # whose geometry actually surrounds the waypoint.
    DENSITY_CELL = 1024
    density = {}    # real_idx -> {(cell_x, cell_y): count}
    for real_idx, raw in per_map_raw.items():
        if not raw: continue
        cells = {}
        for o in raw:
            x = o.get("x"); y = o.get("y")
            if x is None or y is None or x < 256:
                continue   # x<256 = container-depth marker, not a world coord
            key = (x // DENSITY_CELL, y // DENSITY_CELL)
            cells[key] = cells.get(key, 0) + 1
        density[real_idx] = cells

    def density_at(real_idx, wx, wy):
        # Sum the central cell plus its 8 neighbours so a waypoint right
        # at a cell edge still picks up the surrounding population.
        cells = density.get(real_idx)
        if not cells: return 0
        cx, cy = wx // DENSITY_CELL, wy // DENSITY_CELL
        s = 0
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                s += cells.get((cx + dx, cy + dy), 0)
        return s

    def pick_map_for_wp(wp):
        """Pick the map whose object-density at this waypoint is highest.
        Ties on zero density mean no map plausibly contains it — drop."""
        wx, wy = wp["x"], wp["y"]
        best = None
        best_score = 0
        for real_idx in density:
            s = density_at(real_idx, wx, wy)
            if s > best_score:
                best = real_idx
                best_score = s
        return best

    ghost_count = 0
    # Track each NPC's *primary* inferred map so a second pass can use it
    # as a neighbor signal for stationary NPCs that share the boot map.
    npc_primary_map = {}
    for npc_str, entry in schedules.items():
        npc_id = int(npc_str)
        if npc_id not in npc_template: continue   # no sprite to clone

        # Per-waypoint best-fit map by density. Per-NPC consensus map (the
        # one summing the highest density across ALL waypoints) is used as
        # a tiebreaker so a route's outlier dest (e.g. Devon's jail at
        # 2431,3839) doesn't yank that single waypoint onto a dungeon map
        # — it stays on the same consensus map as the rest of the route.
        # Single-waypoint NPCs would otherwise have no consensus signal at
        # all, so we seed the sum with the ITEMCACH home tile's density
        # (those guards live on the Docks meta-map which shares geometry
        # with the rest of Tenebrae, anchoring single-wp guards to the
        # right region).
        consensus_scores = {}
        seed_xys = list((wp["x"], wp["y"]) for wp in entry["wps"])
        if npc_id in npc_home_xy:
            seed_xys.append(npc_home_xy[npc_id])
        for sx, sy in seed_xys:
            for real_idx in density:
                consensus_scores[real_idx] = consensus_scores.get(real_idx, 0) \
                    + density_at(real_idx, sx, sy)
        # ITEMCACH parks the named Tenebrae cast on the "Docks" meta-map
        # (mapnum 3 = real_idx 1) as a boot position before usecode
        # teleports them to their real homes; that signal is misleading.
        # But NPCs whose ITEMCACH home is any *other* real map are pinned
        # there permanently (palace guards, road guards, Necromancer chiefs
        # on their plane, etc.), and the home map is a much stronger prior
        # than per-waypoint density — single-waypoint guards would
        # otherwise lose to whichever dungeon coincidentally has more
        # objects at the waypoint's coord. Anchor consensus with a large
        # bonus for those.
        home_map = npc_home_map.get(npc_id)
        DOCKS_META = 1
        if home_map is not None and home_map != DOCKS_META:
            consensus_scores[home_map] = consensus_scores.get(home_map, 0) + 10000
        consensus = max(consensus_scores, key=consensus_scores.get,
                        default=None) if consensus_scores else None

        wps_by_map = {}
        for wp in entry["wps"]:
            best = pick_map_for_wp(wp)
            # Strong bias toward consensus. Treasure Cove and other dungeons
            # carry object clusters at arbitrary world coords that often
            # overlap city coordinates by chance; without this damping,
            # single waypoints get yanked onto wrong-region maps. A non-
            # consensus map must outweigh consensus by 4× at the waypoint
            # to win, AND deliver a hard minimum local density (so a coord
            # with no plausible map ownership doesn't get force-bucketed).
            if best != consensus and consensus is not None:
                local  = density_at(best,      wp["x"], wp["y"]) if best else 0
                cons_d = density_at(consensus, wp["x"], wp["y"])
                # Only accept non-consensus when consensus has effectively
                # zero density at this coord — that's strong evidence the
                # waypoint is on a different geographic region. A modest
                # density advantage (Treasure Cove edging out West Tenebrae
                # by 5×) is most likely coincidence: many maps have object
                # clusters in coord ranges that overlap city coords.
                if cons_d > 0 and local <= cons_d * 10:
                    best = consensus
            if best is None:
                best = consensus
            if best is None:
                continue
            # Minimum density floor: if even the chosen map only barely
            # covers this coord, the assignment is unreliable. Drop it.
            if density_at(best, wp["x"], wp["y"]) < 20:
                continue
            wp["m"] = best
            wps_by_map.setdefault(best, []).append(wp)

        if consensus is not None:
            npc_primary_map[npc_id] = consensus
        home = npc_home_map.get(npc_id)
        for real_idx, wps in wps_by_map.items():
            if real_idx == home: continue   # already placed by ITEMCACH
            # Pick an anchor whose z matches the modal z of the cluster.
            # A single z=0 outlier (e.g. Mordea's bedroom dest, written
            # before the elevated palace floor coords) would otherwise bury
            # the ghost under the surface.
            z_counts = {}
            for w in wps:
                z_counts[w["z"]] = z_counts.get(w["z"], 0) + 1
            z_mode = max(z_counts, key=z_counts.get)
            anchor = next((w for w in wps if w["z"] == z_mode), wps[0])
            ghost = {
                "x": anchor["x"], "y": anchor["y"], "z": anchor["z"],
                "s": npc_template[npc_id]["s"],
                "f": npc_template[npc_id]["f"],
                "_npc": npc_id,
            }
            per_map_raw.setdefault(real_idx, []).append(ghost)
            ghost_count += 1
    # Stationary NPCs whose ITEMCACH home is the Docks meta-map (real_idx 1)
    # often live "in Tenebrae" per game lore but never move from their boot
    # coords because their class is purely conversational (Salkind the
    # innkeeper, Guard 1 at the gate, etc.). Density inference on their home
    # coords picks a single best-fit map, but the Docks coord ranges overlap
    # multiple Tenebrae sub-region maps AND a few dungeons by chance, so the
    # direct density check is unreliable.
    #
    # Vote by neighbour: for each Docks NPC without a schedule, find the K
    # closest *other* Docks NPCs by Euclidean home-coord distance and use
    # their primary inferred map (from the schedule pass) as a ballot. A
    # clear majority places a ghost there. Salkind sits in the same coord
    # cluster as Mordea / Darion / Tarna / Rhian / Shaana — those NPCs all
    # resolve to West-or-Central Tenebrae via their schedules, so Salkind
    # inherits the consensus.
    import math
    DOCKS_META = 1
    K_NEIGHBOURS = 5
    docks_npcs = [n for n, m in npc_home_map.items() if m == DOCKS_META
                   and n in npc_home_xy]
    stationary = [n for n in docks_npcs if n not in npc_primary_map]
    neighbor_ghost_count = 0
    for npc_id in stationary:
        if npc_id not in npc_template: continue
        hx, hy = npc_home_xy[npc_id]
        # Gather neighbour candidates that themselves have a primary map.
        neighbours = []
        for other in docks_npcs:
            if other == npc_id: continue
            if other not in npc_primary_map: continue
            ox_, oy_ = npc_home_xy[other]
            d = math.hypot(ox_ - hx, oy_ - hy)
            neighbours.append((d, npc_primary_map[other]))
        if not neighbours: continue
        neighbours.sort()
        top = neighbours[:K_NEIGHBOURS]
        votes = {}
        for _, m in top:
            votes[m] = votes.get(m, 0) + 1
        winner, win_votes = max(votes.items(), key=lambda kv: kv[1])
        # Require a real majority (> half of the neighbours surveyed),
        # otherwise the signal is too noisy to act on.
        if win_votes * 2 <= len(top): continue
        if winner == DOCKS_META: continue
        ghost = {
            "x": hx, "y": hy, "z": npc_template[npc_id].get("z", 48),
            "s": npc_template[npc_id]["s"],
            "f": npc_template[npc_id]["f"],
            "_npc": npc_id,
        }
        # parse_npcs records z separately — fall back to a sensible default.
        # (We don't carry z in npc_template above; use ITEMCACH home z if
        # we can recover it from the npcs_by_map placement.)
        per_map_raw.setdefault(winner, []).append(ghost)
        neighbor_ghost_count += 1

    if ghost_count:
        print(f"Placed {ghost_count} schedule-derived ghost NPC markers")
    if neighbor_ghost_count:
        print(f"Placed {neighbor_ghost_count} neighbour-vote ghost NPC markers")

    for real_idx, raw in per_map_raw.items():
        # Resolve GLOBSWAP eggs (usecode class 1200) before glob expansion —
        # teleports parked content into the map's playable area.
        objs = apply_globswap(raw)
        objs = expand_globs(objs, globs)
        objs = apply_collapse(objs)
        # Hatch shape-500 monster eggs into their creature shapes (after glob
        # expansion so eggs carried inside globs are revealed too).
        objs = apply_monster_eggs(objs, atlas_frames)
        # Show the Titans in a manifested pose (before merge_shapes, so the
        # frame's atlas anchor is picked up for the display frame).
        objs = apply_titan_frames(objs)
        merge_shapes(objs, shape_info, typeflags)
        combined.setdefault(real_idx, []).extend(build_render_objects(objs, atlas_frames, shape_info))

    print(f"Writing {len(combined)} map JSON files → {maps_dir}/")
    index = []

    # Per-dialog-key locations across all maps. The spoken-line search uses
    # this to jump to whichever map an NPC (or titan) lives in. Shape-keyed
    # entries cover the titans + the ancient-necromancer aliasing of npc 139.
    DIALOG_SHAPE_KEYS = {1, 80, 109, 385, 433, 623}
    npc_locations = {}

    # Key ↔ lock cross-link. Doors and chests share a lock id with the key
    # that opens them via the quality byte (Pentagram's checkKey / openLock).
    # Indexed by quality so the inspector can list every match across maps.
    lock_index = {}

    # "Any-key" relation. Chests 618/673 unlock via KEYRING::0119, which only
    # consults a lock id when the chest contains a shape-756 marker with
    # high-byte 1 (see comment near LOCK_TRAP_SHAPE). When no such marker is
    # present the bytecode falls through to "matched=true" and any shape-82/79
    # /232 key triggers the FREE::2411 transform — i.e. the chest opens with
    # any key on the map. The keyed lock_index can't express that, so we track
    # those (unkeyed chest, same-map keys) pairs separately and render them as
    # a distinct section in the inspector.
    UNKEYED_CHEST_SHAPES = {618, 673}
    any_key_chests = {}   # map_idx -> [{s, fr}]
    any_key_keys   = {}   # map_idx -> [{s, fr, ks, q}]

    # Per-readable locations across all maps. For each (shape, frame|quality)
    # that resolves to a readable text, list of objects (map + fr + g) so the
    # book/scroll index popup can jump to any instance and reopen the reader
    # modal with the same text the inspector would show.
    read_locations = {}
    def _resolve_readable(shp, fr, q):
        e = readables_for_q.get(str(shp)) or readables_for_q.get(shp)
        if not e: return None
        f_map = e.get("frames") or {}
        q_map = e.get("quality") or {}
        if str(fr) in f_map:  return ("f", fr, f_map[str(fr)])
        if str(q)  in q_map:  return ("q", q,  q_map[str(q)])
        d = e.get("default")
        if d:                  return ("d", None, d)
        return None

    #TEST_MAP = 1   # ← Uncomment this and 2 lines under to only render one map

    for map_idx, render_objs in sorted(combined.items()):
        #if map_idx != TEST_MAP:
        #    continue

        seen_keys = set()
        for it in render_objs:
            o = it["obj"]
            shp = o["s"]
            if shp in DIALOG_SHAPE_KEYS:
                k = f"s{shp}"
                if k not in seen_keys:
                    npc_locations.setdefault(k, []).append(
                        {"m": map_idx, "x": o["x"], "y": o["y"], "z": o["z"]})
                    seen_keys.add(k)
            n = o.get("_npc")
            if n:
                k = str(n)
                if k not in seen_keys:
                    npc_locations.setdefault(k, []).append(
                        {"m": map_idx, "x": o["x"], "y": o["y"], "z": o["z"]})
                    seen_keys.add(k)
            # Key / lock cross-link: doors and chests pack a "lock category"
            # into the high byte of the quality word and the lock id into the
            # low byte; keys just use the lock id directly. Match on the low
            # byte so a key and the doors it opens land in the same bucket.
            # Walks `c` recursively so a key tucked in a chest or NPC pack
            # still surfaces — the entry then focuses on the outermost
            # world-placed container (which is what the viewer can pan to).
            def collect_keylocks(node, container):
                ns = node["s"]
                q = node.get("descq") or 0
                lid = q & 0xFF
                # Shape-756 (Trap) with high-byte == 1: chest lock marker.
                # The low byte is the lock id; the immediate container is the
                # chest the player will navigate to. Without this branch the
                # chest side of every locked-chest pair would be empty
                # because chests themselves carry quality == 0.
                if (ns == LOCK_TRAP_SHAPE and (q >> 8) == 1 and lid
                        and container is not None):
                    lock_index.setdefault(lid, {"key": [], "lock": []})["lock"].append({
                        "m":  map_idx,
                        "s":  container["s"],
                        "fr": container.get("f", 0),
                        "ks": container["s"],
                        "q":  q,
                    })
                elif lid:
                    if ns in KEY_SHAPES:   side = "key"
                    elif ns in LOCK_SHAPES: side = "lock"
                    else:                   side = None
                    if side:
                        focus = container or node
                        lock_index.setdefault(lid, {"key": [], "lock": []})[side].append({
                            "m":  map_idx,
                            "s":  focus["s"],
                            "fr": focus.get("f", 0),
                            "ks": ns,
                            "q":  q,
                        })
                for child in node.get("c") or []:
                    collect_keylocks(child, container or node)
            collect_keylocks(o, None)

            # Any-key relation: only chest shapes 618/673 qualify, and only
            # when no contained shape-756 marker carries a real lock id
            # (high byte 1, low byte non-zero). Keys are collected from every
            # top-level item's contents tree so chest- or pack-held keys also
            # surface as same-map openers.
            if shp in UNKEYED_CHEST_SHAPES:
                has_marker = False
                for child in o.get("c") or []:
                    if child["s"] == LOCK_TRAP_SHAPE:
                        cq = child.get("descq") or 0
                        if (cq >> 8) == 1 and (cq & 0xFF):
                            has_marker = True
                            break
                if not has_marker:
                    any_key_chests.setdefault(map_idx, []).append({
                        "s":  shp,
                        "fr": o.get("f", 0),
                    })
            def collect_any_keys(node, container):
                ns = node["s"]
                if ns in KEY_SHAPES:
                    focus = container or node
                    any_key_keys.setdefault(map_idx, []).append({
                        "s":  focus["s"],
                        "fr": focus.get("f", 0),
                        "ks": ns,
                        "q":  node.get("descq") or 0,
                    })
                for child in node.get("c") or []:
                    collect_any_keys(child, container or node)
            collect_any_keys(o, None)

            # Readable index — one entry per (shape, kind, slot), with each
            # in-world instance listed under .locs so the popup can jump to
            # whichever instance is closest at hand.
            r = _resolve_readable(shp, o.get("f", 0), o.get("descq", 0) or 0)
            if r is not None:
                kind, slot, text = r
                slot_key = "" if slot is None else slot
                rk = f"{shp}:{kind}:{slot_key}"
                ent = read_locations.setdefault(rk, {
                    "s": shp, "k": kind, "sl": slot, "t": text, "locs": [],
                })
                ent["locs"].append({
                    "m": map_idx,
                    "fr": o.get("f", 0),
                    "g":  o.get("descq", 0) or 0,
                })

        sorted_items = topo_sort_objects(render_objs)
        # Manifested Titans are drawn from a tall sprite that extends well
        # beyond the flat egg footprint Pentagram knows about, so the
        # footprint-based painter places them behind anything to their east
        # (e.g. Pyros vs the pillars on Plane of Fire). Lift them to the end
        # of the draw order so they paint on top of nearby static geometry —
        # consistent with how the runtime renders them as actor sprites.
        titan_items = [it for it in sorted_items if it["obj"]["s"] in TITAN_DISPLAY_FRAME]
        if titan_items:
            others = [it for it in sorted_items if it["obj"]["s"] not in TITAN_DISPLAY_FRAME]
            sorted_items = others + titan_items
        sorted_rows = []
        for z_idx, item in enumerate(sorted_items):
            row = item["row"]
            row[3] = z_idx
            sorted_rows.append(row)

        fname = f"map_{map_idx}.json"
        payload = json.dumps(sorted_rows, separators=(",", ":")).encode("utf-8")
        (maps_path / fname).write_bytes(payload)
        # Pre-gzipped sibling so the viewer can fetch it directly and
        # decompress client-side (DecompressionStream). Saves ~2/3 the
        # transfer on every map load with no server-side config required.
        # mtime=0 keeps the archive byte-stable across rebuilds.
        with open(maps_path / (fname + ".gz"), "wb") as raw:
            with gzip.GzipFile(filename="", fileobj=raw,
                                mode="wb", compresslevel=9, mtime=0) as gz:
                gz.write(payload)

        print(f"Wrote map {map_idx} to JSON ({len(payload):,} B)")
        index.append(map_idx)

    # index.json now carries the music track for each map alongside the
    # list of available map ids. `music[map]` is the array of playMusic
    # qualities found in that map's shape-562 MUSIC eggs (usually one).
    index_payload = {
        "maps": index,
        "music": {str(k): v for k, v in sorted(music_by_map.items())},
    }
    with open(maps_path / "index.json", "w", encoding="utf-8") as f:
        json.dump(index_payload, f, separators=(",", ":"))

    print("Loading labels…")
    with open(labels_json, "r", encoding="utf-8") as f:
        labels = json.load(f)
    mapnames_path = Path(labels_json).parent / "mapnames.json"
    mapnames = {}
    if mapnames_path.exists():
        with open(mapnames_path, "r", encoding="utf-8") as f:
            mapnames = json.load(f)

    # NPC number → name, shown in the click-inspect pane for NPC objects.
    npc_path = Path(labels_json).parent / "npc.json"
    npc_names = {}
    if npc_path.exists():
        with open(npc_path, "r", encoding="utf-8") as f:
            npc_names = json.load(f)

    # Per-frame (FLX index, ox, oy) entries for shapes that animate. Sent to
    # the viewer so each frame draws at its own hot-spot. Filtered against
    # atlas_frames (loaded above) so the viewer only references sprites we
    # actually packed — FLX has 1×1 placeholder frames the atlas skips.
    anim_anchors = {}
    # Shapes 578 (big explosion) and 772 (fire explosion) are usecode-spawned
    # FX, so their typeflags carry animationType=0; include them unconditionally
    # so the viewer can play one-shot explosion overlays (trapped chests).
    FX_SHAPES = {578, 772}
    for s_id, tf in typeflags.items():
        if not tf.get("animationType") and s_id not in FX_SHAPES:
            continue
        frames = shape_info.get(s_id - 2, [])
        valid = []
        for f in frames:
            fi = f["fi"]
            if f"{s_id}_{fi}" in atlas_frames:
                valid.append([fi, f["ox"], f["oy"]])
        if valid:
            anim_anchors[s_id] = valid

    if not schedules:
        print("  (no json/schedules.json — run parse_schedules.py; skipping NPC schedule overlay)")

    print("Writing HTML…")
    write_html(index, labels, mapnames, npc_names, image_folder, maps_dir, output_html, anim_anchors, music_by_map, barks, container_gumps, gumpage_areas, npc_locations, read_locations, lock_index, any_key_chests, any_key_keys, schedules)
    print(f"Done → {output_html}")

