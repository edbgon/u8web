        # gump ids carry the +2 atlas bias, so the entry is gump_id - 2.
        cgump_areas = {gn: gumpage_areas[gn - 2]
                       for gn in ccomp if (gn - 2) in gumpage_areas}
        cgump_areas_json = json.dumps(cgump_areas, separators=(",", ":"))
