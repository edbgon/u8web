def count_frames(shape_info, s):
    """Highest FLX frame index + 1 for shape s. Authoritative — sequential
    PNG scanning silently undercounts shapes whose extractor names files
    by FLX frame index (with gaps) or whose first frame isn't fi=0. The
    JS preloader .catch()'es PNGs that don't exist, so overcounting here
    is harmless; undercounting kills the animation entirely."""
    frames = shape_info.get(s - 2, [])
    return max((f["fi"] for f in frames), default=-1) + 1

_frame_count_cache = {}


def build_render_objects(objects, atlas_frames, shape_info):
    out = []
    for obj in objects:
        s, f = obj["s"], obj["f"]
        # The viewer draws every sprite from atlas.png; a (shape, frame) the
        # atlas doesn't carry can't be rendered, so skip emitting a row for it.
        if f"{s}_{f}" not in atlas_frames:
            continue
        ox_ = obj.get("ox", 0)
        oy_ = obj.get("oy", 0)
        x, y, z = obj["x"], obj["y"], obj["z"]

        base_x4 = (x // 4 - y // 4 - ox_) * 4
        base_y4 = (x // 8 + y // 8 - z - oy_) * 4

        # ── iflags bitmask ──────────────────────────────────────────
        tr    = 1 if obj.get("translucent")  else 0
        hide  = 1 if obj.get("hideInGame")   else 0
        solid = 1 if obj.get("solid")        else 0
        occl  = 1 if obj.get("occl")         else 0
        draw  = 1 if obj.get("draw")         else 0
        atype = int(obj.get("animationType") or 0) & 0xF

        xd = obj.get("xd", 32)
        yd = obj.get("yd", 32)
        zd = obj.get("foot_z", 0)
        xd_enc = (xd // 32 - 1) & 0x3   # 32→0, 64→1, 96→2, 128→3
        yd_enc = (yd // 32 - 1) & 0x3
        zd_enc = (zd // 8)      & 0x7   # 0→0, 8→1, 16→2 …

        if obj.get("animationType"):
            if s not in _frame_count_cache:
                _frame_count_cache[s] = count_frames(shape_info, s)
            anim_frames = _frame_count_cache[s]
        else:
            anim_frames = 0

        adata = int(obj.get("animationData") or 0) & 0xF

        iflags = (
            tr
            | (hide  << 1)
            | (solid << 2)
            | (occl  << 3)
            | (draw  << 4)
            | (atype << 5)
            | (xd_enc << 9)
            | (yd_enc << 11)
            | (zd_enc << 13)
            | (adata << 16)
            | (anim_frames << 20)
        )

        info = {"x": x, "y": y, "z": z, "s": s, "f": f}
        if iflags:
            info["if"] = iflags

        if obj.get("g") is not None:
            info["g"] = obj["g"]

        row = [base_x4, base_y4, z, 0, s, f, 0, ox_, oy_, obj.get("sx_img", 0), obj.get("sy_img", 0)]
        if iflags:
            row[6] = iflags
        # Optional positional trailers: [11]=quake, [12]=collapse, [13]=npc,
        # [14]=quality (for books/scrolls/keys, used to pick the description),
        # [15]=contents tree (for containers — see contents_tree()),
        # [16]=teleport destination map index, [17]=teleport id (both for
        # shape-508 teleport eggs — [16] is 0 on a frame-1 landing egg).
        # Trailing zeros are trimmed so most rows carry no trailer at all;
        # when contents (or teleport fields) are present the scalar trailers
        # are kept in full so the later fields land at their fixed indices.
        trailers = [
            obj.get("_quake")    or 0,
            obj.get("_collapse") or 0,
            obj.get("_npc")      or 0,
            obj.get("descq")     or 0,
        ]
        contents = contents_tree(obj["c"]) if obj.get("c") else None
        teledest = obj.get("teledest") or 0
        telid    = obj.get("telid")
        if teledest or telid is not None:
            row.extend(trailers)
            row.append(contents or 0)      # [15]
            row.append(teledest)           # [16]
            row.append(telid or 0)         # [17]
        elif contents:
            row.extend(trailers)
            row.append(contents)
        else:
            while trailers and trailers[-1] == 0:
                trailers.pop()
            row.extend(trailers)

        out.append({"obj": obj, "row": row})
    return out

